#!/usr/bin/env node
/**
 * Generates the @load suite used to compare sharded vs orchestrated execution.
 *
 * 50 spec files x 20 tests = 1000 tests. The file count is what matters for
 * orchestration: the dispatch unit is one spec file, so 50 files across 8
 * machines gives the queue something to balance.
 *
 * Tests never touch the network — page.setContent only — so wall clock reflects
 * scheduling, not storedemo's latency, and nothing here can flake.
 *
 * Files carry deliberately uneven cost (weight 0-4) so LPT has a real ordering
 * problem to solve: the heavy files must go out first or the tail drags.
 */
const fs = require('fs');
const path = require('path');

const FILES = 50;
const TESTS_PER_FILE = 20;
const OUT = path.join(__dirname, '..', 'tests', 'load');

const body = (i, t, weight) => `
  test('load ${i}-${t}: renders and asserts @load @load-w${weight}', async ({ page }) => {
    await page.setContent(\`<main id="app"><h1>spec ${i}</h1><ul>\${
      Array.from({ length: 8 }, (_, n) => \`<li data-item="\${n}">item \${n}</li>\`).join('')
    }</ul></main>\`);
    await expect(page.locator('h1')).toHaveText('spec ${i}');
    await expect(page.locator('li')).toHaveCount(8);
    await expect(page.locator('[data-item="3"]')).toHaveText('item 3');${
      weight ? `\n    await page.waitForTimeout(${weight * 40});` : ''
    }
  });
`;

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (f.endsWith('.spec.ts')) fs.unlinkSync(path.join(OUT, f));

let total = 0;
for (let i = 1; i <= FILES; i++) {
  const weight = i % 5; // 0..4 — uneven by design, so LPT has something to order
  const id = String(i).padStart(2, '0');
  const tests = Array.from({ length: TESTS_PER_FILE }, (_, t) => body(id, t + 1, weight)).join('');
  fs.writeFileSync(
    path.join(OUT, `load-${id}.spec.ts`),
    `import { test, expect } from '@playwright/test';\n\n` +
    `// GENERATED by scripts/generate-load-tests.js — do not edit by hand.\n` +
    `// weight ${weight} (${weight * 40}ms of deliberate cost per test)\n\n` +
    `test.describe('load suite ${id}', { tag: ['@load'] }, () => {${tests}});\n`
  );
  total += TESTS_PER_FILE;
}
console.log(`generated ${FILES} files, ${total} tests in ${OUT}`);
